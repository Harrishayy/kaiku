"""Generate Kaiku's look for every platform from the design ground truth (stdlib only).

    uv run python design/gen.py            # write design/generated/{tokens.css,Tokens.swift} + design/mascot.svg
    uv run python design/gen.py --check    # exit 1 if any generated file is stale (used by design/tests)
    uv run python design/gen.py --out DIR  # write into DIR instead (same relative layout)

Inputs:  design/tokens.json (colours, glow, radii, spacing, type, motion)
         design/mascot.spec.json (geometry, pivots, states)
Outputs: generated/tokens.css     CSS custom properties, light + dark (prefers-color-scheme + data-theme)
         generated/Tokens.swift   `KaikuTokens` enum for SwiftUI (iOS + macOS)
         mascot.svg               the mascot with every part as a named group (200x200)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUTS = ("generated/tokens.css", "generated/Tokens.swift", "mascot.svg")


def _load() -> tuple[dict, dict]:
    tokens = json.loads((HERE / "tokens.json").read_text())
    spec = json.loads((HERE / "mascot.spec.json").read_text())
    return tokens, spec


def _num(v: float) -> str:
    return f"{v:g}"


def _camel(name: str) -> str:
    parts = name.replace("_", "-").split("-")
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return f"s{out}" if out[:1].isdigit() else out


# ------------------------------------------------------------------ CSS
def render_css(t: dict) -> str:
    light, dark = t["color"]["light"], t["color"]["dark"]
    lines = [
        "/* GENERATED by design/gen.py from design/tokens.json — do not edit. Run `make design`. */",
        f"/* Kaiku tokens v{t['version']}. Fonts: {t['type']['google-fonts']} */",
        ":root {",
    ]
    lines += [f"  --k-{k}: {v};" for k, v in light.items()]
    for sem, ref in t["color"]["$semantic"].items():
        lines.append(f"  --k-{sem}: var(--k-{ref});")
    for k, v in t["radius"].items():
        lines.append(f"  --k-radius-{k}: {v}px;")
    for k, v in t["space"].items():
        lines.append(f"  --k-space-{k}: {v}px;")
    for k, v in t["size"].items():
        lines.append(f"  --k-size-{k}: {v}px;")
    for k, v in t["type"]["family"].items():
        lines.append(f"  --k-font-{k}: {v['web']};")
    for k, v in t["type"]["scale"].items():
        lines.append(f"  --k-text-{k}: {v['weight']} {v['size']}px/{v['line']}px var(--k-font-body);")
        lines.append(f"  --k-text-{k}-size: {v['size']}px;")
    for k, v in t["motion"]["duration"].items():
        lines.append(f"  --k-dur-{k}: {v}ms;")
    for k, v in t["motion"]["easing"].items():
        lines.append(f"  --k-ease-{k}: cubic-bezier({', '.join(_num(x) for x in v)});")
    seen: set[str] = set()
    for s in t["glow"]["stops"]:
        if s["name"] not in seen:
            seen.add(s["name"])
            lines.append(f"  --k-glow-{s['name']}: {s['color']};")
    lines += ["  --k-glow: var(--k-glow-day);", "  --k-glow-intensity: 0.9;", "  --k-motion: 1;", "}", ""]
    dark_body = [f"  --k-{k}: {v};" for k, v in dark.items()] + ["  color-scheme: dark;"]
    lines += ['@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {']
    lines += ["  " + ln for ln in dark_body]
    lines += ["  }", "}", "", ':root[data-theme="dark"] {', *dark_body, "}", ""]
    lines += ["@media (prefers-reduced-motion: reduce) {", "  :root { --k-motion: 0; }", "}", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ Swift
def _hex(v: str) -> str:
    return "0x" + v.lstrip("#").upper()


def render_swift(t: dict) -> str:
    light, dark = t["color"]["light"], t["color"]["dark"]
    m = t["motion"]
    out = [
        "// GENERATED by design/gen.py from design/tokens.json — do not edit. Run `make design`.",
        f"// Kaiku tokens v{t['version']}. Mascot geometry: design/mascot.spec.json (bundle it as a resource).",
        "import SwiftUI",
        "#if canImport(UIKit)",
        "import UIKit",
        "#elseif canImport(AppKit)",
        "import AppKit",
        "#endif",
        "",
        "public enum KaikuTokens {",
        "    public enum Colors {",
    ]
    for k in light:
        out.append(f"        public static let {_camel(k)} = SwiftUI.Color(kaikuLight: {_hex(light[k])}, dark: {_hex(dark[k])})")
    for sem, ref in t["color"]["$semantic"].items():
        out.append(f"        public static var {_camel(sem)}: SwiftUI.Color {{ {_camel(ref)} }}")
    out += ["    }", "", "    public enum Radius {"]
    out += [f"        public static let {_camel(k)}: CGFloat = {v}" for k, v in t["radius"].items()]
    out += ["    }", "", "    public enum Space {"]
    out += [f"        public static let {_camel(k)}: CGFloat = {v}" for k, v in t["space"].items()]
    out += ["    }", "", "    public enum Size {"]
    out += [f"        public static let {_camel(k)}: CGFloat = {v}" for k, v in t["size"].items()]
    out += ["    }", "", "    /// SF Pro Rounded on Apple: Font.system(size:weight:design: .rounded).", "    public enum TextStyle {"]
    for k, v in t["type"]["scale"].items():
        out.append(f"        public static let {_camel(k)} = KaikuTextStyle(size: {v['size']}, lineHeight: {v['line']}, weight: {v['weight']})")
    out += ["    }", "", "    /// Seconds.", "    public enum Duration {"]
    out += [f"        public static let {_camel(k)}: Double = {_num(v / 1000)}" for k, v in m["duration"].items()]
    out += ["    }", "", "    public enum Easing {"]
    for k, v in m["easing"].items():
        a, b, c, d = (_num(x) for x in v)
        out.append(f"        public static func {_camel(k)}(_ duration: Double) -> Animation {{ .timingCurve({a}, {b}, {c}, {d}, duration: duration) }}")
    out += ["    }", "", "    public enum Spring {"]
    for k, v in m["spring"].items():
        out.append(f"        public static let {_camel(k)} = Animation.spring(response: {_num(v['response'])}, dampingFraction: {_num(v['damping'])})")
    out += ["    }", "", "    public enum Blink {"]
    for k, v in m["blink"].items():
        val = _num(v / 1000) if k.endswith(("interval", "gap")) else _num(v)
        out.append(f"        public static let {_camel(k)}: Double = {val}")
    out += ["    }", "", "    public enum IdleBreath {"]
    out += [f"        public static let {_camel(k)}: Double = {_num(v)}" for k, v in m["idle-breath"].items()]
    out += ["    }", "", "    public enum GuideBreath {"]
    out += [f"        public static let {_camel(k)}: Double = {_num(v)}" for k, v in m["guide-breath"].items()]
    out += ["    }", "", "    /// Chest glow by local hour; interpolate linearly between stops, wrapping at 24.", "    public static let glowStops: [KaikuGlowStop] = ["]
    for s in t["glow"]["stops"]:
        out.append(f"        KaikuGlowStop(hour: {_num(s['hour'])}, name: \"{s['name']}\", color: {_hex(s['color'])}, intensity: {_num(s['intensity'])}),")
    out += [
        "    ]",
        "}",
        "",
        "public struct KaikuTextStyle: Sendable {",
        "    public let size: CGFloat",
        "    public let lineHeight: CGFloat",
        "    public let weight: Int",
        "    public var font: Font { .system(size: size, weight: fontWeight, design: .rounded) }",
        "    public var fontWeight: Font.Weight {",
        "        switch weight { case ..<450: return .regular; case ..<550: return .medium; case ..<650: return .semibold; case ..<750: return .bold; default: return .heavy }",
        "    }",
        "}",
        "",
        "public struct KaikuGlowStop: Sendable {",
        "    public let hour: Double",
        "    public let name: String",
        "    public let color: UInt32",
        "    public let intensity: Double",
        "}",
        "",
        "extension SwiftUI.Color {",
        "    init(kaikuHex hex: UInt32) {",
        "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255,",
        "                  blue: Double(hex & 0xFF) / 255, opacity: 1)",
        "    }",
        "",
        "    init(kaikuLight light: UInt32, dark: UInt32) {",
        "        #if canImport(UIKit)",
        "        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(SwiftUI.Color(kaikuHex: dark)) : UIColor(SwiftUI.Color(kaikuHex: light)) })",
        "        #elseif canImport(AppKit)",
        "        self.init(nsColor: NSColor(name: nil) { appearance in",
        "            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua",
        "                ? NSColor(SwiftUI.Color(kaikuHex: dark)) : NSColor(SwiftUI.Color(kaikuHex: light))",
        "        })",
        "        #else",
        "        self.init(kaikuHex: light)",
        "        #endif",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


# ------------------------------------------------------------------ SVG
def _style(shape: dict, light: dict) -> str:
    def paint(ref: str) -> str:
        if ref == "none":
            return "none"
        if ref == "glow":
            return "url(#kaiku-glow-grad)" if shape.get("gradient") == "radial" else f"var(--k-glow, {day})"
        return f"var(--k-{ref}, {light[ref]})"

    day = light["glow"]

    css = []
    if "fill" in shape:
        css.append(f"fill:{paint(shape['fill'])}")
    if "stroke" in shape:
        css.append(f"stroke:{paint(shape['stroke'])}")
        css.append(f"stroke-width:{_num(shape.get('stroke-width', 1))}")
        for k in ("stroke-linecap", "stroke-linejoin"):
            if k in shape:
                css.append(f"{k}:{shape[k]}")
    if "opacity" in shape:
        css.append(f"opacity:{_num(shape['opacity'])}")
    return ";".join(css)


def _shape(s: dict, light: dict) -> str:
    st = _style(s, light)
    if s["type"] == "path":
        return f'<path d="{s["d"]}" style="{st}"/>'
    if s["type"] == "ellipse":
        return f'<ellipse cx="{_num(s["cx"])}" cy="{_num(s["cy"])}" rx="{_num(s["rx"])}" ry="{_num(s["ry"])}" style="{st}"/>'
    if s["type"] == "circle":
        return f'<circle cx="{_num(s["cx"])}" cy="{_num(s["cy"])}" r="{_num(s["r"])}" style="{st}"/>'
    raise ValueError(f"unknown shape type {s['type']!r}")


def _part(p: dict, light: dict, depth: int) -> list[str]:
    pad = "  " * depth
    px, py = p["pivot"]
    style = f"transform-box:view-box;transform-origin:{_num(px)}px {_num(py)}px"
    if "opacity" in p.get("default", {}):
        style += f";opacity:{_num(p['default']['opacity'])}"
    lines = [f'{pad}<g id="{p["id"]}" data-pivot="{_num(px)} {_num(py)}" style="{style}">']
    lines += [f"{pad}  {_shape(s, light)}" for s in p.get("shapes", [])]
    for c in p.get("children", []):
        if "clip" in c:
            lines.append(f'{pad}  <g clip-path="url(#kaiku-clip-{c["clip"]})">')
            lines += _part(c, light, depth + 2)
            lines.append(f"{pad}  </g>")
        else:
            lines += _part(c, light, depth + 1)
    lines.append(f"{pad}</g>")
    return lines


def render_svg(t: dict, spec: dict) -> str:
    day = next(s["color"] for s in t["glow"]["stops"] if s["name"] == "day")
    light = {**t["color"]["light"], "glow": day}
    vb = " ".join(_num(v) for v in spec["viewBox"])
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" width="200" height="200" role="img" aria-label="Kaiku">',
        "  <!-- GENERATED by design/gen.py from design/mascot.spec.json + tokens.json — do not edit. Run `make design`. -->",
        "  <!-- Colours read the k- CSS custom properties from design/generated/tokens.css when inlined; light fallbacks otherwise. -->",
        "  <defs>",
        '    <radialGradient id="kaiku-glow-grad">',
        f'      <stop offset="0" style="stop-color:var(--k-glow, {day});stop-opacity:1"/>',
        f'      <stop offset="1" style="stop-color:var(--k-glow, {day});stop-opacity:0"/>',
        "    </radialGradient>",
    ]
    for cid, c in spec["clips"].items():
        shape = _shape(c, light).replace(' style=""', "")
        lines.append(f'    <clipPath id="kaiku-clip-{cid}">{shape}</clipPath>')
    lines.append("  </defs>")
    for p in spec["parts"]:
        lines += _part(p, light, 1)
    lines += ["</svg>", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ main
def render_all() -> dict[str, str]:
    tokens, spec = _load()
    return {
        "generated/tokens.css": render_css(tokens),
        "generated/Tokens.swift": render_swift(tokens),
        "mascot.svg": render_svg(tokens, spec),
    }


def stale(root: Path = HERE) -> list[str]:
    return [rel for rel, text in render_all().items() if not (root / rel).is_file() or (root / rel).read_text() != text]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=HERE, help="output root (default: design/)")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    a = ap.parse_args(argv)
    if a.check:
        bad = stale(a.out)
        for rel in bad:
            print(f"stale: design/{rel} (run `make design`)", file=sys.stderr)
        return 1 if bad else 0
    for rel, text in render_all().items():
        path = a.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
