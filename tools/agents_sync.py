"""Keep the agent context (one AGENTS.md per module) in sync with modules.toml (the module ground truth).

    python tools/agents_sync.py          # regenerate the module index in AGENTS.md, then check
    python tools/agents_sync.py --check  # check only (used by `make test`); exit 1 on problems

One file per folder, no redundancy: AGENTS.md is read natively by Claude Code (>= 2.1.281, only when no CLAUDE.md
exists), Codex, Cursor, and by Gemini CLI via .gemini/settings.json `context.fileName`. So:
  1. every module folder has AGENTS.md, and NO CLAUDE.md / GEMINI.md / README.md (README.md only at the repo root)
  2. non-docs modules' AGENTS.md has the standard sections (MODULE_SECTIONS)
  3. no CLAUDE.md / GEMINI.md at the root; .gemini/settings.json points Gemini CLI at AGENTS.md
  4. every message type a module emits/consumes exists in kaiku_contracts
  5. every obs.* type has at least one real (non-harness) producer and one consumer
  6. the generated module index in the root AGENTS.md matches modules.toml
  7. config/criteria.toml is valid and every enabled metric/rule reads an obs type some real module emits
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kaiku_contracts import OBS, REGISTRY  # noqa: E402

MODULE_SECTIONS = ["Purpose", "Consumes", "Emits", "Invariants", "Run standalone", "Run with sim", "Config & env",
                   "Health signal", "Tests", "Known issues"]
FORBIDDEN = ("CLAUDE.md", "GEMINI.md", "README.md")  # redundant with AGENTS.md
BEGIN = "<!-- BEGIN MODULE INDEX (generated by `make agents` from modules.toml; do not edit by hand) -->"
END = "<!-- END MODULE INDEX -->"


def load_modules(root: Path = ROOT) -> list[dict]:
    return tomllib.loads((root / "modules.toml").read_text())["module"]


def render_index(modules: list[dict]) -> str:
    lines = [BEGIN, "", "| module | path | owner | kind | removable | what |", "|---|---|---|---|---|---|"]
    for m in modules:
        lines.append(f"| {m['name']} | [`{m['path']}/`]({m['path']}/AGENTS.md) | {m['owner']} | {m['kind']} | "
                     f"{'yes' if m.get('removable') else 'no'} | {m['summary']} |")
    lines += ["", END]
    return "\n".join(lines)


def check(root: Path = ROOT, fix: bool = False) -> list[str]:
    problems: list[str] = []
    modules = load_modules(root)
    names = [m["name"] for m in modules]
    if len(names) != len(set(names)):
        problems.append("modules.toml: duplicate module names")

    for m in modules:
        d = root / m["path"]
        tag = f"{m['name']} ({m['path']})"
        if not d.is_dir():
            problems.append(f"{tag}: folder missing")
            continue
        agents_md = d / "AGENTS.md"
        if not agents_md.is_file():
            problems.append(f"{tag}: AGENTS.md missing (copy docs/templates/module/AGENTS.template.md)")
        elif m["kind"] != "docs":
            text = agents_md.read_text()
            missing = [h for h in MODULE_SECTIONS if f"\n## {h}" not in text]
            if missing:
                problems.append(f"{tag}: AGENTS.md missing sections: {', '.join(missing)}")
        for name in FORBIDDEN:
            if (d / name).exists() or (d / name).is_symlink():
                problems.append(f"{tag}: remove {name} — fold its content into AGENTS.md (one file per module)")
        for field in ("emits", "consumes"):
            for t in m.get(field, []):
                if t not in REGISTRY:
                    problems.append(f"{tag}: {field} unknown message type {t!r} (not in kaiku_contracts)")

    real = [m for m in modules if m["kind"] != "harness"]
    for t in sorted(OBS):
        if not any(t in m.get("emits", []) for m in real):
            problems.append(f"{t}: no module emits it (add a producer or remove the type)")
        if not any(t in m.get("consumes", []) for m in real):
            problems.append(f"{t}: no module consumes it")

    # every enabled criteria metric/rule must read data some real module actually produces
    try:
        from kaiku_contracts.criteria import load_criteria

        crit = load_criteria(root / "config" / "criteria.toml")
        for item in [*crit.metrics, *crit.rules]:
            if getattr(item, "enabled", True) and not any(item.obs in m.get("emits", []) for m in real):
                problems.append(f"criteria {item.name}: reads {item.obs}, which no module emits")
    except FileNotFoundError:
        pass
    except Exception as e:  # invalid criteria file
        problems.append(f"config/criteria.toml invalid: {str(e).splitlines()[0]}")

    for name in ("CLAUDE.md", "GEMINI.md"):
        if (root / name).exists() or (root / name).is_symlink():
            problems.append(f"remove root {name}: it stops Claude Code / duplicates AGENTS.md")
    gem = root / ".gemini" / "settings.json"
    try:
        names = json.loads(gem.read_text())["context"]["fileName"]
        if "AGENTS.md" not in ([names] if isinstance(names, str) else names):
            raise KeyError
    except (OSError, KeyError, ValueError, TypeError):
        problems.append('.gemini/settings.json must set {"context": {"fileName": ["AGENTS.md"]}}')

    agents = root / "AGENTS.md"
    text = agents.read_text()
    want = render_index(modules)
    if BEGIN in text and END in text:
        current = text[text.index(BEGIN): text.index(END) + len(END)]
        if current != want:
            if fix:
                agents.write_text(text.replace(current, want))
            else:
                problems.append("AGENTS.md module index is stale (run `make agents`)")
    else:
        problems.append("AGENTS.md: module index markers missing")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    problems = check(fix=not a.check)
    if problems:
        print("agent/module sync problems:", *problems, sep="\n  - ", file=sys.stderr)
        return 1
    print(f"agents in sync ({len(load_modules())} modules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
